package cli

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"cppm/internal/project"
)

func cmdClean() *Command {
	build := func() (*flag.FlagSet, *bool) {
		all := false
		fs := newFlagSet("clean")
		fs.BoolVar(&all, "all", false, "also delete .cppm/ generated files")
		return fs, &all
	}
	return &Command{
		Name:    "clean",
		Summary: "delete build output",
		Usage:   "cppm clean [flags]",
		Long: `Removes build/. With --all, also removes .cppm/, which is regenerated by
the next sync or build.

Never touches cppm.json, cppm.lock or CMakeLists.txt.`,
		flagSet: func() *flag.FlagSet { fs, _ := build(); return fs },
		Run: func(args []string) error {
			fs, all := build()
			if err := parseArgs(fs, args); err != nil {
				return err
			}
			p, err := project.Open(mustCwd())
			if err != nil {
				return err
			}
			targets := []string{filepath.Join(p.Root, "build")}
			if *all {
				targets = append(targets, filepath.Join(p.Root, project.DirName))
			}
			for _, t := range targets {
				if _, err := os.Stat(t); os.IsNotExist(err) {
					fmt.Printf("  absent   %s\n", relTo(p.Root, t))
					continue
				}
				if err := os.RemoveAll(t); err != nil {
					return fmt.Errorf("remove %s: %w", t, err)
				}
				fmt.Printf("  removed  %s\n", relTo(p.Root, t))
			}
			return nil
		},
	}
}
